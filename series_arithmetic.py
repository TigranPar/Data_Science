"""37 առաջադրանք՝ series_tasks (1).docx ֆայլից․ թվաբանական գործողություններ և արժեքների ընտրություն։"""

import pandas as pd


def solve(s: pd.Series) -> dict:
    if s.empty:
        raise ValueError("Այս առաջադրանքների համար անհրաժեշտ է ոչ դատարկ Series։")

    # Յուրաքանչյուր առաջադրանք կատարվում է սկզբնական s-ի հետ՝ մյուսներից անկախ։
    even_indices = s.copy()
    even_indices.loc[even_indices.index % 2 == 0] *= 10
    total = s.sum()
    percentages = s / total * 100 if total != 0 else pd.Series(
        float("nan"), index=s.index
    )
    return {
        "01. Յուրաքանչյուր տարրին գումարել 5": s + 5,
        "02. Յուրաքանչյուր տարրից հանել 10": s - 10,
        "03. Բոլոր տարրերը բազմապատկել 2-ով": s * 2,
        "04. Բոլոր տարրերը բաժանել 5-ի": s / 5,
        "05. Տարրերի քառակուսիները": s ** 2,
        "06. Տարրերի խորանարդները": s ** 3,
        "07. Series-ի յուրաքանչյուր տարրին գումարել 100": s + 100,
        "08. Բաժանել 2-ի և կլորացնել": (s / 2).round(),
        "09. Յուրաքանչյուր տարրից հանել առաջին տարրը": s - s.iloc[0],
        "10. Յուրաքանչյուր տարրը բազմապատկել վերջին տարրով": s * s.iloc[-1],
        "11. Հաշվել s * 3 + 10": s * 3 + 10,
        "12. Հաշվել (s - 5) / 5": (s - 5) / 5,
        "13. Տարրերի գումարը": s.sum(),
        "14. Միջին արժեքը": s.mean(),
        "15. Առավելագույն և նվազագույն արժեքների տարբերությունը": s.max() - s.min(),
        "16. Տարրերի արտադրյալը": s.prod(),
        "17. Յուրաքանչյուր տարրի համար հաշվել 2x + 1": 2 * s + 1,
        "18. Զույգ ինդեքսներով արժեքները բազմապատկել 10-ով": even_indices,
        "19. Ստուգել, թե որ տարրերն են մեծ 20-ից": s > 20,
        "20. Ստուգել, թե որ տարրերն են փոքր 15-ից": s < 15,
        "21. Ստուգել հավասարությունը 33-ին": s == 33,
        "22. Ստուգել, թե որ տարրերն են մեծ կամ հավասար 25-ի": s >= 25,
        "23. Ստուգել, թե որ տարրերն են փոքր կամ հավասար 10-ի": s <= 10,
        "24. Ստուգել բաժանելիությունը 5-ի": s % 5 == 0,
        "25. Ստուգել բաժանելիությունը 4-ի": s % 4 == 0,
        "26. Ստուգել, թե որ տարրերն են դրական": s > 0,
        "27. Ընտրել 10-ից մեծ արժեքները": s[s > 10],
        "28. Ընտրել 10-ից մեծ և 30-ից փոքր արժեքները": s[(s > 10) & (s < 30)],
        "29. Ընտրել 10-ից փոքր կամ 30-ից մեծ արժեքները": s[(s < 10) | (s > 30)],
        "30. Ընտրել և՛ 2-ի, և՛ 5-ի բաժանվող թվերը": s[(s % 2 == 0) & (s % 5 == 0)],
        "31. Ընտրել 2-ի չբաժանվող թվերը": s[s % 2 != 0],
        "32. Ստուգել, թե որ արժեքներն են միջինից մեծ": s > s.mean(),
        "33. Ստուգել 40 արժեքի առկայությունը": bool((s == 40).any()),
        "34. 20-ից մեծ տարրերի քանակը": int((s > 20).sum()),
        "35. [10, 30] միջակայքի արժեքների քանակը": int(((s >= 10) & (s <= 30)).sum()),
        "36. Տեսակավորել 15-ից մեծ արժեքները": s[s > 15].sort_values(),
        "37. Յուրաքանչյուր արժեքի տոկոսային բաժինը ընդհանուր գումարում, %": percentages,
    }


def main():
    s = pd.Series([5, 10, 15, 20, 25, 30, 33, 40], name="numbers")
    print("ՍԿԶԲՆԱԿԱՆ SERIES\n", s, sep="")
    for task, result in solve(s).items():
        print(f"\n{task}\n{result}")


if __name__ == "__main__":
    main()
